/**
 * 模式表：带插值的文案按形状认。
 * ------------------------------------------------------------------
 * 上游有大量文案是模板串拼出来的（`Page ${n}`、`Column ${i + 1}`），
 * 永远不可能成为词典的键，只能按形状认。
 *
 * 每条都是**锚定正则**（`^…$`，不带 `g`）。替换函数返回**空串**表示
 * 「这条不适用」，让文案保持英文并出现在缺口报告里——宁可半句英文，
 * 也别拼出「重置 Reset all」这种半成品。
 *
 * 第二参数 `t` 是翻译函数：捕获组若是界面文案（方位、标签、单位名）
 * 就用 `t(组)` 递归再翻一次；若是用户数据（文件名、样式名、批注人）
 * 就原样保留。
 *
 * ⚠️ **顺序即优先级**，从具体到宽泛：先「带单位的设置项」，再各类
 * 定位句式，然后通用动作，最后才是 `X options` 这类宽泛式。
 * ⚠️ `i18n-report.mjs` 不统计模式表，它只按词典算覆盖率——
 * 本文件的效果要在运行时看，别拿报告的百分比验收。
 */
